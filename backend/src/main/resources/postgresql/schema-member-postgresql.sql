-- ============================================================
-- 1. godo_member — 고도몰 회원 (기본 정보)
-- ============================================================
CREATE TABLE IF NOT EXISTS godo_member (
    -- 식별자
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_no          BIGINT          NOT NULL UNIQUE,  -- 고도몰 회원 번호 (upsert 키)
    mem_id          TEXT            NOT NULL UNIQUE,  -- 로그인 아이디

    -- 등급·승인
    group_sno       INTEGER         NOT NULL DEFAULT 1,         -- 회원 등급 (1~9)
    member_fl       TEXT            NOT NULL DEFAULT 'personal',-- personal / business
    app_fl          TEXT            NOT NULL DEFAULT 'n',       -- y: 승인 / n: 미승인
    app_dt          TEXT,                                       -- 가입 승인일

    -- 기본 정보
    mem_name        TEXT,                   -- 이름 [AES-256-GCM]
    mem_name_hash   TEXT,                   -- 이름 검색용 SHA-256
    nick_name       TEXT,                   -- 닉네임
    sex_fl          TEXT,                   -- m: 남 / w: 여
    birth_dt        TEXT,                   -- 생년월일 [AES-256-GCM]
    marri_fl        TEXT,                   -- y: 기혼 / n: 미혼
    marri_date      TEXT,                   -- 결혼기념일
    job             TEXT,                   -- 직업
    interest        TEXT,                   -- 관심분야 ('|' 구분)

    -- 연락처
    email           TEXT,                   -- 이메일 [AES-256-GCM]
    email_hash      TEXT,                   -- 이메일 검색용 SHA-256
    cell_phone      TEXT,                   -- 휴대폰 [AES-256-GCM]
    cell_phone_hash TEXT,                   -- 휴대폰 검색용 SHA-256
    phone           TEXT,                   -- 전화번호 [AES-256-GCM]
    fax             TEXT,                   -- 팩스번호
    mailling_fl     TEXT        NOT NULL DEFAULT 'y',  -- y: 수신 / n: 거부
    sms_fl          TEXT        NOT NULL DEFAULT 'y',  -- y: 수신 / n: 거부

    -- 주소 [AES-256-GCM] — 우편번호 포함 단일 문자열
    address         TEXT,                   -- 주소 전체 [AES-256-GCM]

    -- 활동·통계
    entry_dt        TEXT,                   -- 회원가입일
    entry_path      TEXT        NOT NULL DEFAULT 'pc',  -- pc / mobile
    last_login_dt   TEXT,                   -- 최종 로그인일
    login_count     INTEGER     NOT NULL DEFAULT 0,     -- 방문횟수
    sale_amount     DOUBLE PRECISION NOT NULL DEFAULT 0, -- 주문금액
    mileage         DOUBLE PRECISION NOT NULL DEFAULT 0, -- 마일리지
    deposit         DOUBLE PRECISION NOT NULL DEFAULT 0, -- 예치금

    -- 추천인
    recomm_id       TEXT,

    -- 에쓰푸드몰 추가 정보
    ex1             TEXT,                   -- 업종
    ex2             TEXT,                   -- 세금계산서 발행 여부
    ex3             TEXT,                   -- 담당자
    ex4             TEXT,
    ex5             TEXT,
    ex6             TEXT,

    -- 개인정보
    expiration_fl   INTEGER     NOT NULL DEFAULT 1,  -- 유효기간 (1/3/5/999)

    -- 기타
    memo            TEXT,                   -- 남기는말씀

    -- 시스템
    deleted_fl      TEXT        NOT NULL DEFAULT 'n', -- 소프트 삭제 (y/n)
    synced_at       TEXT        NOT NULL,             -- 마지막 동기화 시각
    created_at      TEXT        NOT NULL,
    updated_at      TEXT        NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_godo_member_group_sno        ON godo_member(group_sno);
CREATE INDEX IF NOT EXISTS idx_godo_member_app_fl           ON godo_member(app_fl);
CREATE INDEX IF NOT EXISTS idx_godo_member_member_fl        ON godo_member(member_fl);
CREATE INDEX IF NOT EXISTS idx_godo_member_entry_dt         ON godo_member(entry_dt);
CREATE INDEX IF NOT EXISTS idx_godo_member_deleted_fl       ON godo_member(deleted_fl);
CREATE INDEX IF NOT EXISTS idx_godo_member_email_hash       ON godo_member(email_hash);
CREATE INDEX IF NOT EXISTS idx_godo_member_cell_phone_hash  ON godo_member(cell_phone_hash);
CREATE INDEX IF NOT EXISTS idx_godo_member_mem_name_hash    ON godo_member(mem_name_hash);


-- ============================================================
-- 2. godo_member_business — 사업자 정보
-- ============================================================
CREATE TABLE IF NOT EXISTS godo_member_business (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_no          BIGINT      NOT NULL UNIQUE,  -- godo_member.mem_no (FK)

    -- 사업자 정보
    company         TEXT,
    business_no     TEXT,                   -- 사업자번호 XXX-XX-XXXXX [평문 저장]
    ceo_name        TEXT,                   -- 대표자명 [AES-256-GCM]
    service_name    TEXT,                   -- 업태명
    service_code    TEXT,                   -- 업태 공통코드 (common_code 매칭)
    item_name       TEXT,                   -- 종목명
    item_code       TEXT,                   -- 종목 공통코드 (common_code 매칭)

    -- 사업장 주소 [AES-256-GCM] — 우편번호 포함 단일 문자열
    com_address     TEXT,                   -- 사업장 주소 [AES-256-GCM]

    -- 사업자등록증
    biz_license_file TEXT,                  -- 사업자등록증 파일명

    -- 시스템
    duplicate_mem_no TEXT,                  -- 중복 여부 (Req 12)
    created_at       TEXT        NOT NULL,
    updated_at       TEXT        NOT NULL,

    CONSTRAINT fk_godo_member_business_mem_no
        FOREIGN KEY (mem_no) REFERENCES godo_member(mem_no)
);

CREATE INDEX IF NOT EXISTS idx_godo_member_business_business_no
    ON godo_member_business(business_no);


-- ============================================================
-- 3. godo_member_business_log — 사업자 정보 변경 이력
-- ============================================================
CREATE TABLE IF NOT EXISTS godo_member_business_log (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_no           BIGINT  NOT NULL,  -- 참조, FK 없음 (원본 삭제 후에도 이력 유지)

    -- 변경 전 상태 스냅샷 (godo_member_business 동일 구성)
    company          TEXT,
    business_no      TEXT,
    ceo_name         TEXT,              -- [AES-256-GCM] 2026-07-03 수정
    service_name     TEXT,
    service_code     TEXT,
    item_name        TEXT,
    item_code        TEXT,
    com_address      TEXT,              -- [AES-256-GCM] 2026-07-03 수정
    biz_license_file TEXT,

    -- 로그 정보
    logged_at        TEXT NOT NULL,     -- 변경 발생 시각 (저장 직전)
    logged_by        TEXT,              -- 변경 수행자 (세션 이메일)
    created_at       TEXT NOT NULL      -- 로그 저장 시각
);

CREATE INDEX IF NOT EXISTS idx_godo_member_business_log_mem_no
    ON godo_member_business_log(mem_no);
CREATE INDEX IF NOT EXISTS idx_godo_member_business_log_logged_at
    ON godo_member_business_log(logged_at);


-- ============================================================
-- 4. member_partner — 거래처 정보 (Req 12 최종)
-- ============================================================
CREATE TABLE IF NOT EXISTS member_partner (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_no            BIGINT      NOT NULL UNIQUE,  -- godo_member.mem_no (FK)

    -- 거래처 정보
    partner_code      TEXT,                         -- ERP 거래처 코드
    partner_name      TEXT,                         -- 거래처명
    tax_invoice_fl    TEXT        NOT NULL DEFAULT 'n',  -- y: 세금계산서 / n: 미신청

    -- 거래처 상태 (Req 12: partner_registered_fl 폐지, member_status로 통일)
    -- 허용값: UNREGISTERED(미등록) / NORMAL(정상) / INACTIVE(불용)
    member_status     TEXT        NOT NULL DEFAULT 'UNREGISTERED',

    -- 시스템
    created_at        TEXT        NOT NULL,
    updated_at        TEXT        NOT NULL,

    CONSTRAINT fk_member_partner_mem_no
        FOREIGN KEY (mem_no) REFERENCES godo_member(mem_no)
);

CREATE INDEX IF NOT EXISTS idx_member_partner_partner_code
    ON member_partner(partner_code);
CREATE INDEX IF NOT EXISTS idx_member_partner_member_status
    ON member_partner(member_status);


-- ============================================================
-- 5. member_partner_log — 거래처 정보 변경 이력
-- ============================================================
CREATE TABLE IF NOT EXISTS member_partner_log (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_no        BIGINT  NOT NULL,  -- 참조, FK 없음

    -- 변경 전 상태 스냅샷 (member_partner 동일 구성)
    partner_code  TEXT,
    partner_name  TEXT,
    tax_invoice_fl TEXT,
    member_status TEXT,

    -- 로그 정보
    logged_at     TEXT NOT NULL,     -- 변경 발생 시각
    logged_by     TEXT,              -- 변경 수행자
    created_at    TEXT NOT NULL      -- 로그 저장 시각
);

CREATE INDEX IF NOT EXISTS idx_member_partner_log_mem_no
    ON member_partner_log(mem_no);
CREATE INDEX IF NOT EXISTS idx_member_partner_log_logged_at
    ON member_partner_log(logged_at);


-- ============================================================
-- 6. common_code — 공통 코드 (업태/업종 등)
-- ============================================================
CREATE TABLE IF NOT EXISTS common_code (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code  TEXT NOT NULL,   -- 그룹코드 (SERVICE, ITEM 등)
    group_name  TEXT NOT NULL,   -- 그룹명
    code        TEXT NOT NULL,   -- 코드값
    code_name   TEXT NOT NULL,   -- 코드명
    note        TEXT,            -- 비고
    use_yn      TEXT NOT NULL DEFAULT 'Y',  -- Y: 사용 / N: 미사용
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL,

    UNIQUE (group_code, code)
);

CREATE INDEX IF NOT EXISTS idx_common_code_group_code
    ON common_code(group_code);


-- ============================================================
-- Req 12 마이그레이션: 거래처 상태 통합
-- (partner_registered_fl → member_status)
-- 기존 DB에서 partner_registered_fl이 있으면 member_status로 변환 후 컬럼 삭제
-- ============================================================
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'member_partner' AND column_name = 'partner_registered_fl'
    ) THEN
        -- 등록 여부를 거래처 상태로 변환
        UPDATE member_partner
           SET member_status = CASE
               WHEN partner_registered_fl = 'y' THEN 'NORMAL'
               ELSE 'UNREGISTERED'
           END
         WHERE member_status IS NULL OR member_status = 'NORMAL';

        -- 기존 컬럼 삭제
        ALTER TABLE member_partner DROP COLUMN partner_registered_fl;
    END IF;
END $$;

-- 로그 테이블에서 obsolete 컬럼 제거 (이미 스냅샷으로 저장된 이력은 유지)
ALTER TABLE IF EXISTS member_partner_log DROP COLUMN IF EXISTS partner_registered_fl;

-- 인덱스 정리
DROP INDEX IF EXISTS idx_member_partner_registered_fl;
